export const languageOptions = [
  { code: "en", shortLabel: "EN", label: "English", locale: "en-US" },
  { code: "ru", shortLabel: "RU", label: "Русский", locale: "ru-RU" },
  { code: "es", shortLabel: "ES", label: "Español", locale: "es-ES" },
  { code: "de", shortLabel: "DE", label: "Deutsch", locale: "de-DE" },
  { code: "fr", shortLabel: "FR", label: "Français", locale: "fr-FR" },
  { code: "zh", shortLabel: "ZH", label: "中文", locale: "zh-CN" },
] as const;

export type Language = (typeof languageOptions)[number]["code"];

const STORAGE_KEY = "cai-language";
const DESKTOP_PREFERENCES_ENDPOINT = "/v1/cai/desktop/preferences";

function normalizeLanguage(value: unknown): Language | null {
  const normalized = String(value ?? "").trim().toLowerCase();
  return languageOptions.some((item) => item.code === normalized)
    ? (normalized as Language)
    : null;
}

async function fetchDesktopLanguage(): Promise<Language | null> {
  if (!browser) {
    return null;
  }
  try {
    const response = await fetch(DESKTOP_PREFERENCES_ENDPOINT, {
      headers: { Accept: "application/json" },
    });
    if (!response.ok) {
      return null;
    }
    const payload = await response.json();
    return normalizeLanguage(payload?.language);
  } catch {
    return null;
  }
}

async function persistDesktopLanguage(language: Language): Promise<void> {
  if (!browser) {
    return;
  }
  try {
    await fetch(DESKTOP_PREFERENCES_ENDPOINT, {
      method: "PUT",
      headers: {
        "Content-Type": "application/json",
        Accept: "application/json",
      },
      body: JSON.stringify({ language }),
    });
  } catch {
    // Desktop preference sync is best-effort only.
  }
}

