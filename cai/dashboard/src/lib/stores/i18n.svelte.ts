const sourceTranslations: Partial<Record<Language, Record<string, string>>> = {
  ru: sourceRu,
  es: sourceEs,
  de: sourceDe,
  fr: sourceFr,
  zh: sourceZh,
};

function languageOption(language: Language) {
  return (
    languageOptions.find((item) => item.code === language) ?? languageOptions[0]
  );
}

function nextLanguage(language: Language): Language {
  const index = languageOptions.findIndex((item) => item.code === language);
  return languageOptions[(index + 1) % languageOptions.length].code;
}

function interpolate(
  template: string,
  values: Record<string, InterpolationValue> = {},
): string {
  return template.replace(/\{(\w+)\}/g, (_match, key: string) =>
    values[key] == null ? "" : String(values[key]),
  );
}

function defaultLanguage(): Language {
  if (!browser) {
    return "en";
  }
  const saved = normalizeLanguage(localStorage.getItem(STORAGE_KEY));
  if (saved) {
    return saved;
  }
  return "en";
}

class I18nStore {
  language = $state<Language>(defaultLanguage());

  constructor() {
    if (browser) {
      void this.hydrateDesktopLanguage();
    }
  }

  async hydrateDesktopLanguage(): Promise<void> {
    if (!browser) {
      return;
    }
    if (normalizeLanguage(localStorage.getItem(STORAGE_KEY))) {
      return;
    }
    const desktopLanguage = await fetchDesktopLanguage();
    if (!desktopLanguage) {
      return;
    }
    this.language = desktopLanguage;
    localStorage.setItem(STORAGE_KEY, desktopLanguage);
  }

  setLanguage(language: Language): void {
    this.language = language;
    if (browser) {
      localStorage.setItem(STORAGE_KEY, language);
    }
    void persistDesktopLanguage(language);
  }

  toggleLanguage(): void {
    this.setLanguage(nextLanguage(this.language));
  }

  t(key: TranslationKey): string {
    return translations[this.language][key] ?? translations.en[key] ?? key;
  }

  tr(source: string): string {
    return sourceTranslations[this.language]?.[source] ?? source;
  }

  trf(source: string, values: Record<string, InterpolationValue> = {}): string {
    return interpolate(this.tr(source), values);
  }

  locale(): string {
    return languageOption(this.language).locale;
  }
}

export const i18nStore = new I18nStore();
export const currentLanguage = () => i18nStore.language;
export const currentLanguageOption = () => languageOption(i18nStore.language);
export const setLanguage = (language: Language) => i18nStore.setLanguage(language);
export const toggleLanguage = () => i18nStore.toggleLanguage();
export const t = (key: TranslationKey) => i18nStore.t(key);
export const tr = (source: string) => i18nStore.tr(source);
export const trf = (
  source: string,
  values: Record<string, InterpolationValue> = {},
) => i18nStore.trf(source, values);
export const currentLocale = () => i18nStore.locale();
